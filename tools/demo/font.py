def glyph_tile(rows, colour=1):
    """16 bytes: a glyph drawn in colour 1-3 on a see-through background."""
    lo, hi = [0] * 8, [0] * 8
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == '1':
                bit = 0x80 >> (x + 1)
                if colour & 1:
                    lo[y + 1] |= bit
                if colour & 2:
                    hi[y + 1] |= bit
    return bytes(lo + hi)


def font_bytes(colour=1):
    """Tiles 20-5F (1 KB), to be placed at offset 200 of a pattern table."""
    out = bytearray(0x400)
    for ch, rows in GLYPHS.items():
        n = ord(ch) - 0x20
        out[n * 16:n * 16 + 16] = glyph_tile(rows, colour)
    return bytes(out)


def digit_tile(n, colour=2):
    return glyph_tile(GLYPHS[str(n % 10)], colour)
